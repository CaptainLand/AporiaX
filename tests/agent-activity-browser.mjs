import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.TEST_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(`${server.resolvedUrls.local[0]}tests/fixtures/route-activity.html`);
  const count = (role) => page.locator(`[data-agent-role="${role}"] b`);
  await count('builder').waitFor();
  assert.equal(await count('main').innerText(), '1');
  assert.equal(await count('builder').innerText(), '1');
  assert.equal(await count('curator').innerText(), '0');
  assert.match(await page.getByTestId('builder-capacity').innerText(), /1 \/ 4/);
  await page.evaluate(() => {
    window.routeFixture.emit({ type: 'subagent.started', agentId: 'builder-1', activationId: 'builder-1:1', role: 'builder' });
    window.routeFixture.emit({ type: 'subagent.started', agentId: 'builder-2', activationId: 'builder-2:1', role: 'builder', task: '实现帮助页' });
    window.routeFixture.emit({ type: 'agent_budget.queue', builderConcurrency: 4, runningBuilders: 2, queuedBuilders: 1 });
  });
  assert.equal(await count('builder').innerText(), '2');
  await page.evaluate(() => window.routeFixture.emit({ type: 'control.paused', pauseReasons: ['network'] }));
  await page.locator('.ra-state').filter({ hasText: '等待网络恢复' }).waitFor();
  assert.equal(await count('builder').innerText(), '2', 'Pause must not reset worker activation counts');
  await page.evaluate(() => window.routeFixture.emit({ type: 'control.paused', pauseReasons: ['network', 'user'] }));
  await page.locator('.ra-state').filter({ hasText: '手动暂停' }).waitFor();
  await page.evaluate(() => window.routeFixture.emit({ type: 'control.paused', pauseReasons: ['sleep'] }));
  await page.locator('.ra-state').filter({ hasText: '系统暂停' }).waitFor();
  await mkdir('.tmp/route-activity', { recursive: true });
  await page.screenshot({ path: '.tmp/route-activity/preview100-suspended.png', fullPage: true });
  await page.evaluate(() => window.routeFixture.emit({ type: 'control.resumed', pauseReasons: [] }));
  await page.locator('.ra-state').filter({ hasText: '执行中' }).waitFor();
  assert.match(await page.getByTestId('builder-capacity').innerText(), /2 \/ 4/);
  assert.match(await page.getByTestId('builder-capacity').innerText(), /排队 1/);
  await page.evaluate(() => window.routeFixture.emit({ type: 'subagent.completed', agentId: 'builder-2', activationId: 'builder-2:1', status: 'completed', acceptance: { status: 'pending' } }));
  await page.locator('.ra-event-meta').getByText('待验收', { exact: true }).waitFor();
  await page.evaluate(() => window.routeFixture.emit({ type: 'subagent.reviewed', agentId: 'builder-2', acceptance: { status: 'accepted', reason: '已核对实现，测试未运行。' } }));
  await page.locator('.ra-event-meta').getByText('已接受', { exact: true }).waitFor();
  await mkdir('.tmp/route-activity', { recursive: true });
  await page.screenshot({ path: '.tmp/route-activity/agent-counts-light.png', fullPage: true });
  await page.getByRole('button', { name: '选择任务轮次', exact: true }).click();
  await page.locator('.ra-run-list button').last().click();
  assert.equal(await count('builder').innerText(), '—');
  assert.match(await page.locator('.ra-agent-legacy').innerText(), /旧记录/);
  await page.getByRole('button', { name: '回到最新一轮', exact: true }).click();
  assert.equal(await count('builder').innerText(), '2');
  await page.evaluate(() => window.routeFixture.emit({ type: 'turn.completed' }));
  assert.match(await page.getByTestId('builder-capacity').innerText(), /0 \/ 4/);
  assert.match(await page.getByTestId('builder-capacity').innerText(), /峰值 2/);
  await page.setViewportSize({ width: 430, height: 900 });
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
  assert(await page.locator('.ra-agents').evaluate((element) => element.scrollWidth <= element.clientWidth));
  await page.screenshot({ path: '.tmp/route-activity/agent-counts-dark-narrow.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Agent activity browser: role counts, dedup, custom concurrency/queue, pending/accepted results, history isolation and narrow dark layout: PASS');
} finally { await browser?.close(); await server.close(); }
