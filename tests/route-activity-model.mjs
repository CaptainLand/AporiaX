import assert from 'node:assert/strict';
import { createWitnessMonitor } from '../electron/witness-monitor.js';
import { collectTaskRouteRuns } from '../src/p0-model.js';
import { reduceHarnessTaskEvent } from '../src/state/harness-event-reducer.js';
import { activeRouteRecords, activityActor, activityElapsed, describeRouteRecord, routeActivityRecords, routeRunLabel } from '../src/conversation/route-activity-model.js';

let clock = Date.parse('2026-09-21T00:00:00Z');
const monitor = createWitnessMonitor({ heartbeatMs: 0, now: () => clock });
const send = (event) => { clock += 1000; monitor.observe(event); return monitor.snapshot(); };
send({ type: 'turn.started' });
send({ type: 'tool.started', tool: 'read_file', callId: 'read', path: 'missing.md' });
let witness = send({ type: 'tool.completed', tool: 'read_file', callId: 'read', path: 'missing.md', success: false, error: 'ENOENT: missing file', exitCode: 1 });
let record = witness.records.at(-1);
assert.equal(record.error, 'ENOENT: missing file');
assert.equal(record.detail, record.error);
assert.equal(record.path, 'missing.md');
assert.equal(record.exitCode, 1);
assert.match(describeRouteRecord(record).detail, /ENOENT/);
assert.equal(record.lastActivityAt, record.completedAt);
send({ type: 'subagent.started', agentId: 'build', role: 'builder', task: 'Implement feature' });
send({ type: 'subagent.tool.started', agentId: 'build', role: 'builder', callId: 'same', tool: 'write_file', path: 'src/a.js' });
send({ type: 'subagent.started', agentId: 'verify', role: 'verify', task: 'Test feature' });
send({ type: 'subagent.tool.started', agentId: 'verify', role: 'verify', callId: 'same', tool: 'run_command', command: 'npm test' });
witness = send({ type: 'response.reset', round: 2 });
let run = { status: 'running', witness };
assert.equal(activeRouteRecords(routeActivityRecords(run)).length, 3, 'One current tool per agent, plus main response');
assert.equal(activityActor({ actor: 'subagent', role: 'builder' }), '构建 Agent');
assert.equal(activityActor({ actor: 'subagent', role: 'planner' }), 'planner Agent');
assert.equal(describeRouteRecord({ kind: 'tool', tool: 'run_command' }).title, '运行命令');
assert.equal(describeRouteRecord({ kind: 'tool', tool: 'custom', capability: { stage: 'lens', titleZh: '查询目录', titleEn: 'Query catalog' } }).title, '查询目录');
clock += 10000;
witness = send({ type: 'response.activity', content: 'INTERNAL_DATA_NOT_FOR_UI' });
assert.equal(witness.records.at(-1).lastActivityAt, new Date(clock).toISOString());
assert.equal(JSON.stringify(witness).includes('INTERNAL_DATA_NOT_FOR_UI'), false);
assert.equal(activityElapsed(witness.records.at(-1), clock), 11000);
witness = send({ type: 'response.retry', reason: 'HTTP 429', attempt: 2 });
assert.equal(witness.records.at(-1).status, 'retry');
assert.equal(describeRouteRecord(witness.records.at(-1)).title, '模型请求重试');
witness = send({ type: 'subagent.tool.completed', agentId: 'build', callId: 'same', tool: 'write_file', success: true, exitCode: 0, detail: 'Saved' });
assert.equal(witness.records.find((r) => r.agentId === 'verify' && r.kind === 'tool').status, 'running');
assert.equal(witness.records.find((r) => r.agentId === 'build' && r.kind === 'tool').exitCode, 0);
witness = send({ type: 'subagent.completed', agentId: 'build', status: 'partial', summary: 'One file pending' });
assert.equal(witness.records.find((r) => r.kind === 'agent' && r.agentId === 'build').status, 'partial');
witness = send({ type: 'control.paused' });
assert.ok(activeRouteRecords(routeActivityRecords({ status: 'running', witness })).every((r) => r.status === 'paused'));
send({ type: 'control.resumed' });
witness = send({ type: 'turn.completed', status: 'partial' });
assert.equal(routeRunLabel({ status: 'running', witness }), '部分完成');
assert.equal(activeRouteRecords(routeActivityRecords({ status: 'partial', witness })).length, 0);
assert.equal(routeRunLabel({ status: 'completed', selfCheck: { delivery: { status: 'unverified' } } }), '已交付 · 未验证');
assert.equal(routeRunLabel({ status: 'interrupted', witness: { status: 'running' } }), '已停止');
assert.equal(routeActivityRecords({ status: 'completed', witness: { records: [{ id: 'stale', kind: 'tool', eventType: 'tool.started', status: 'completed' }] } })[0].status, 'unknown');
assert.equal(activeRouteRecords(routeActivityRecords({ status: 'completed', witness: { records: [{ id: 'stale', status: 'running' }] } })).length, 0);

const witnessed = collectTaskRouteRuns({ messages: [{ id: 'witness-only', role: 'assistant', status: 'completed', witness: { records: [{ id: 'done', eventType: 'turn.completed', status: 'completed' }] } }] });
assert.equal(witnessed.length, 1, 'Witness-only runs must remain in history');
const synthetic = collectTaskRouteRuns({ messages: [{ id: 'live', role: 'assistant', status: 'running', changes: [{ path: 'new.js' }], witness: { records: [{ id: 'actual', kind: 'thinking', status: 'running' }] } }] })[0];
assert.equal(routeActivityRecords(synthetic).length, 1, 'Never mix synthetic compatibility delivery steps into actual events');
const merged = routeActivityRecords({ status: 'running', rawEntries: [{ id: 'renderer', agentId: 'a', callId: 'a:c', status: 'failed', error: 'Saved error', exitCode: 2 }], witness: { records: [{ id: 'w', kind: 'tool', agentId: 'a', callId: 'c', status: 'failed' }] } });
assert.equal(merged.length, 1); assert.equal(merged[0].error, 'Saved error'); assert.equal(merged[0].exitCode, 2);
const legacy = routeActivityRecords({ status: 'completed', entries: [{ id: 'old', title: 'Old action', startedAt: '2026-09-21T00:00:00Z', finishedAt: '2026-09-21T00:00:05Z', status: 'completed' }] });
assert.equal(legacy[0].elapsedMs, 5000);
assert.equal(describeRouteRecord(legacy[0]).title, 'Old action');

let tasks = [{ id: 'task', messages: [{ id: 'assistant', role: 'assistant', route: [] }] }];
const ref = { taskId: 'task', assistantId: 'assistant' };
const reduce = (event) => { tasks = reduceHarnessTaskEvent(tasks, ref, { runId: 'run', ...event }); return tasks[0].messages[0].route; };
reduce({ type: 'tool.started', tool: 'run_command', callId: 'one', command: 'npm test' });
reduce({ type: 'tool.completed', tool: 'run_command', callId: 'one', success: false, error: 'test failed', exitCode: 1 });
reduce({ type: 'tool.started', tool: 'run_command', callId: 'two', command: 'npm run build' });
let route = reduce({ type: 'tool.completed', tool: 'run_command', callId: 'two', success: true });
assert.equal(route[0].status, 'failed', 'An unrelated successful command must not mark a failure recovered');
assert.equal(route[0].error, 'test failed'); assert.equal(route[0].exitCode, 1);
reduce({ type: 'tool.started', tool: 'run_command', callId: 'three', command: 'npm test' });
route = reduce({ type: 'tool.completed', tool: 'run_command', callId: 'three', success: true });
assert.equal(route[0].status, 'recovered');
route = reduce({ type: 'subagent.tool.started', agentId: 'b', role: 'builder', tool: 'write_file', callId: 'sub' });
assert.match(route.at(-1).title, /Builder/);
route = reduce({ type: 'subagent.tool.completed', agentId: 'b', tool: 'write_file', callId: 'sub', success: false, error: 'EACCES' });
assert.equal(route.at(-1).error, 'EACCES');

for (let i = 0; i < 510; i++) send({ type: 'plan.updated', plan: { revision: i } });
assert.equal(monitor.snapshot().records.length, 500);
assert.ok(monitor.snapshot().omittedRecords > 0);
monitor.dispose();
console.log('Route activity model: PASS (Witness integrity, roles, retries, outcomes, history, compatibility, recovery scope).');
