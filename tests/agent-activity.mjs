import assert from 'node:assert/strict';
import { createWitnessMonitor } from '../electron/witness-monitor.js';
import { routeAgentActivity, activityRecordStatus } from '../src/conversation/route-activity-model.js';
const monitor = createWitnessMonitor({ heartbeatMs: 0 });
const send = (event) => { monitor.observe(event); return monitor.snapshot(); };
send({ type: 'turn.started', agentBudget: { builderConcurrency: 4 } });
const start = { type: 'subagent.started', agentId: 'b1', role: 'builder', activationId: 'b1:1' };
send(start); send(start);
for (let i = 0; i < 30; i++) send({ type: 'response.reset', round: i });
let snapshot = send({ type: 'agent_budget.queue', builderConcurrency: 4, runningBuilders: 1, queuedBuilders: 2 });
assert.equal(snapshot.agentActivity.roles.main.activations, 1);
assert.equal(snapshot.agentActivity.roles.builder.activations, 1);
assert.equal(snapshot.agentActivity.builder.queued, 2);
send({ type: 'subagent.completed', agentId: 'b1', activationId: 'b1:1', acceptance: { status: 'pending' } });
send({ ...start, activationId: 'b1:2' });
send({ ...start, agentId: 'b2', activationId: 'b2:1' });
snapshot = send({ type: 'agent_budget.queue', builderConcurrency: 4, runningBuilders: 2, queuedBuilders: 0 });
assert.equal(snapshot.agentActivity.roles.builder.activations, 3);
assert.equal(snapshot.agentActivity.builder.running, 2);
assert.equal(snapshot.agentActivity.builder.peak, 2);
for (const role of ['explore', 'review', 'verify', 'curator']) send({ type: 'subagent.started', role, agentId: role, activationId: `${role}:1` });
for (let i = 0; i < 600; i++) send({ type: 'instructions.loaded', detail: `Rule ${i}` });
snapshot = send({ type: 'subagent.cancelled', agentId: 'b2' });
assert(snapshot.omittedRecords > 0);
assert.equal(snapshot.agentActivity.roles.builder.activations, 3, 'Counters survive bounded log retention');
assert.equal(snapshot.agentActivity.builder.running, 1);
assert.equal(snapshot.agentActivity.roles.curator.activations, 1);
snapshot = send({ type: 'turn.failed' });
assert.equal(snapshot.agentActivity.builder.running, 0);
assert.equal(snapshot.agentActivity.builder.limit, 4);
assert.equal(snapshot.agentActivity.roles.main.active, 0);
assert.equal(routeAgentActivity({ status: 'completed', witness: snapshot }).builder.running, 0);
assert.equal(routeAgentActivity({ witness: { records: [] } }).roles.builder.activations, null);
assert.equal(activityRecordStatus({ kind: 'agent', status: 'completed', acceptance: { status: 'pending' } }), '待验收');
const restored = createWitnessMonitor({ heartbeatMs: 0, initialAgentActivity: snapshot.agentActivity });
restored.observe({ type: 'turn.started', agentBudget: { builderConcurrency: 2 } });
assert.equal(restored.snapshot().agentActivity.roles.builder.activations, 3);
assert.equal(restored.snapshot().agentActivity.builder.running, 0);
assert.equal(restored.snapshot().agentActivity.builder.limit, 2);
monitor.dispose(); restored.dispose();
console.log('Per-run Agent activity: dedup, continuation, role counts, queue, custom concurrency, retention, terminal and recovery: PASS');
