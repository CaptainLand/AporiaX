import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRemoteCommandInbox, remoteOwnerKey } from '../electron/account/remote-command-inbox.js';
const dir = await mkdtemp(join(tmpdir(), 'aporia-remote-inbox-'));
const path = join(dir, 'inbox.sqlite');
const owner = remoteOwnerKey('https://api.invalid', 'user', 'device');
let inbox;
try {
  inbox = createRemoteCommandInbox(path);
  const command = { id: 'one', type: 'prompt', localTaskId: 'task', payload: { prompt: 'Do something once' } };
  inbox.ingest(owner, [command, command]); assert.equal(inbox.pending(owner).length, 1);
  const claim = inbox.claim(owner, command.id);
  assert.ok(claim.claim); assert.equal(inbox.claim(owner, command.id), null);
  assert.throws(() => inbox.executing(owner, command.id, 'forged'), /CLAIM/);
  inbox.complete(owner, command.id, claim.claim, 'accepted', 'Queued');
  inbox.complete(owner, command.id, claim.claim, 'failed', 'ACK network outage');
  assert.equal(inbox.receipts(owner)[0].status, 'accepted');
  inbox.close(); inbox = createRemoteCommandInbox(path);
  inbox.ingest(owner, [command]); assert.equal(inbox.pending(owner).length, 0);
  assert.equal(inbox.receipts(owner)[0].result, 'Queued');
  inbox.acknowledge(owner, 'one'); assert.equal(inbox.receipts(owner).length, 0);
  assert.throws(() => inbox.ingest(owner, [{ ...command, payload: { prompt: 'Changed' } }]), /CONTENT_CHANGED/);
  const next = { ...command, id: 'two' }; inbox.ingest(owner, [next]); inbox.claim(owner, 'two');
  inbox.close(); inbox = createRemoteCommandInbox(path);
  assert.match(inbox.receipts(owner)[0].result, /UNCERTAIN/);
  assert.equal(inbox.claim(owner, 'two'), null, 'restart cannot replay uncertain effects');
  const other = remoteOwnerKey('https://api.invalid', 'other-user', 'device');
  assert.equal(inbox.pending(other).length, 0);
  assert.throws(() => inbox.complete(other, 'one', claim.claim, 'completed', ''), /CLAIM/);
  inbox.ingest(owner, [{ ...command, id: 'view-reload' }, { ...command, id: 'other-view' }]);
  inbox.claim(owner, 'view-reload', 'view1'); inbox.claim(owner, 'other-view', 'view2');
  inbox.abandon('view1');
  assert.match(inbox.receipts(owner).find((item) => item.id === 'view-reload').result, /UNCERTAIN/);
  assert.ok(!inbox.receipts(owner).some((item) => item.id === 'other-view'));
  console.log('Remote inbox: durable claim, dedupe, restart, ACK-only retry, uncertainty, identity/content isolation: PASS');
} finally { inbox?.close(); await rm(dir, { recursive: true, force: true }); }
