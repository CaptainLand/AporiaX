import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false, watch: null } });
await server.listen();
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1300, height: 1000 }, bypassCSP: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(10000);
  await page.goto(server.resolvedUrls.local[0] + 'tests/fixtures/professional-roles.html');
  const roles = page.getByRole('region', { name: '专业角色配置' });
  await roles.getByLabel('名称', { exact: true }).waitFor();
  assert.equal(await roles.getByRole('navigation', { name: '角色列表' }).getByRole('button').count(), 6);
  await roles.getByLabel('Builder 并发上限').fill('3');
  await roles.getByRole('button', { name: '新增角色', exact: true }).click();
  await roles.getByLabel('名称', { exact: true }).fill('前端审查');
  await roles.getByRole('textbox', { name: '职责', exact: true }).fill('核对界面和证据');
  await roles.getByRole('textbox', { name: '角色指令', exact: true }).fill('只使用观察到的证据。');
  await roles.getByRole('combobox', { name: '执行模板', exact: true }).selectOption('verify');
  await roles.getByRole('combobox', { name: '模型', exact: true }).selectOption(JSON.stringify(['fixture', 'specialist']));
  await roles.locator('.pr-capabilities summary').click();
  await roles.getByLabel('Fixture Skill', { exact: true }).check();
  await roles.getByLabel('Local fixture · Fixture check', { exact: true }).check();
  await roles.getByLabel('run_command', { exact: true }).uncheck();
  await roles.getByRole('combobox', { name: /^项目知识/ }).selectOption('read');
  await roles.getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => window.fixture.saved.revision === 1);
  const saved = await page.evaluate(() => window.fixture.saved);
  assert.equal(saved.builderLimit, 3); assert.equal(saved.profiles.length, 6);
  assert(saved.profiles.at(-1).skills.includes('fixture-skill'));
  assert(saved.profiles.at(-1).mcpTools.includes('mcp__fixture__check'));
  assert(!saved.profiles.at(-1).tools.includes('run_command'));
  await roles.getByLabel('名称', { exact: true }).fill('');
  await roles.getByRole('button', { name: '保存', exact: true }).click();
  await roles.getByRole('alert').waitFor(); assert.match(await roles.getByRole('alert').innerText(), /不能为空/);
  await roles.getByLabel('名称', { exact: true }).fill('前端审查');
  await roles.getByLabel('配置范围').selectOption('task');
  assert.equal(await roles.getByLabel('Builder 并发上限').inputValue(), '0', 'legacy explicit zero preserved');
  await roles.getByRole('button', { name: '恢复当前任务继承' }).click();
  assert.equal(await roles.getByLabel('Builder 并发上限').inputValue(), '3');
  await roles.getByRole('combobox', { name: /^思考强度/ }).selectOption('high');
  await roles.getByRole('button', { name: '保存', exact: true }).click();
  await page.waitForFunction(() => window.fixture.task?.builderLimit === null);
  assert.equal(await page.evaluate(() => window.fixture.task.professionalRoles.profiles[window.fixture.saved.profiles.at(-1).id].thinking), 'high');
  await roles.getByLabel('配置范围').selectOption('global');
  await roles.getByRole('button', { name: '复制角色', exact: true }).click();
  assert.equal(await roles.getByLabel('名称', { exact: true }).inputValue(), '前端审查 副本');
  await roles.getByRole('button', { name: '删除角色', exact: true }).click();
  await roles.getByRole('button', { name: '前端审查', exact: true }).click();
  const panel = page.getByRole('region', { name: '专业 Agent', exact: true });
  assert.equal(await panel.locator('details[open]').count(), 0);
  await panel.locator('summary').click();
  assert.match(await panel.innerText(), /部分未知/); assert.match(await panel.innerText(), /无可靠计价/);
  await panel.getByLabel('追加要求', { exact: true }).fill('请补充验证证据');
  await panel.getByRole('button', { name: '追加要求', exact: true }).click();
  await panel.getByRole('button', { name: '停止此 Agent' }).click();
  assert.deepEqual((await page.evaluate(() => window.fixture.calls)).map(item => [item.kind, item.taskId, item.runId, item.agentId]), [['steer', 'fixture', 'run-fixture', 'agent-fixture'], ['stop', 'fixture', 'run-fixture', 'agent-fixture']]);
  await mkdir('.tmp/qa', { recursive: true });
  const geometry = [];
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    geometry.push(await roles.boundingBox());
    await page.screenshot({ path: `.tmp/qa/professional-roles-${theme}.png`, fullPage: true });
  }
  assert.deepEqual(geometry[0], geometry[1], 'same day/night geometry');
  await page.setViewportSize({ width: 560, height: 900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'no narrow-screen overflow');
  await page.screenshot({ path: '.tmp/qa/professional-roles-narrow.png', fullPage: true });
  await page.evaluate(() => window.fixture.end());
  await panel.getByText('本轮已结束；如需继续，请在主聊天发送下一轮要求。').waitFor();
  assert.equal(await panel.getByRole('button').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Professional role UI: CRUD, validation, task inheritance, abilities, guidance/stop, theme parity, narrow screen PASS');
} finally { await browser.close(); await server.close(); }
