import assert from "node:assert/strict";
import { mkdir } from 'node:fs/promises';
import { createServer } from "vite";
import { chromium } from "playwright-core";

const server = await createServer({ server: { host: "127.0.0.1", port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.TEST_BROWSER || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(server.resolvedUrls.local[0] + "tests/fixtures/composer-workbench.html?reasoning=claude");
  const trigger = page.getByRole('button', { name: '切换思考强度', exact: true });
  const effort = page.getByRole('dialog', { name: '思考强度', exact: true });
  const openEffort = async () => { await trigger.click(); await effort.waitFor(); };
  await openEffort();
  const slider = effort.getByRole('slider', { name: '思考强度', exact: true });
  assert.equal(await slider.getAttribute('max'), '4');
  assert.equal(await effort.locator('svg, button, .effort-slider-copy').count(), 0, 'no icons, reset control or model subtitle');
  assert.doesNotMatch(await effort.innerText(), /Opus|Claude/);
  assert.equal(await effort.evaluate(el => el.scrollWidth > el.clientWidth), false, "five effort levels must fit the menu");
  const thinking = page.getByRole("switch", { name: "深度思考" });
  assert.equal(await thinking.count(), 0, 'deep thinking switch removed');
  for (const [index, [label, value]] of [["Low", "low"], ["Medium", "medium"], ["High", "high"], ["XHigh", "xhigh"], ["Max", "max"]].entries()) {
    await slider.press('Home');
    for (let i = 0; i < index; i++) await slider.press('ArrowRight');
    assert.equal(await page.evaluate(() => window.fixtureTask.effort), value);
    assert.equal(await slider.getAttribute('aria-valuetext'), label);
    assert.equal(await effort.isVisible(), true, 'slider remains visible during adjustment');
  }
  await page.waitForFunction(() => document.querySelector('.effort-gem')?.dataset.state === 'animated');
  const canvasSize = await effort.locator('canvas').evaluate(el => [el.width, el.height]);
  const bounds = await slider.boundingBox();
  const inset = 15;
  const pointerX = bounds.x + inset + 2 + (bounds.width - inset * 2) * .37;
  await page.mouse.move(bounds.x + bounds.width - inset + 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(pointerX, bounds.y + bounds.height / 2, { steps: 8 });
  await page.waitForFunction(x => {
    const rect = document.querySelector('.effort-slider-thumb').getBoundingClientRect();
    return Math.abs(rect.x + rect.width / 2 - x) < 1;
  }, pointerX);
  const drag = await effort.evaluate(el => {
    const thumb = el.querySelector('.effort-slider-thumb');
    const fill = el.querySelector('.effort-slider-fill');
    const thumbRect = thumb.getBoundingClientRect(), fillRect = fill.getBoundingClientRect();
    return { center: thumbRect.x + thumbRect.width / 2, fillEnd: fillRect.right, thumbEnd: thumbRect.right, transition: getComputedStyle(thumb).transitionDuration };
  });
  assert(Math.abs(drag.center - pointerX) < 1, 'thumb tracks the pointer between valid effort stops');
  assert(Math.abs(drag.fillEnd - drag.thumbEnd) < 1, 'thumb covers the fill end without a protruding blue edge');
  assert.equal(drag.transition, '0s', 'no lagging transition while dragging');
  await effort.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.deepEqual(await effort.locator('canvas').evaluate(el => [el.width, el.height]), canvasSize, 'drag clips a fixed-size shader instead of reallocating its framebuffer');
  assert.equal(await effort.locator('.effort-slider-thumb').evaluate(el => el.getBoundingClientRect().width), 26);
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), 'max', 'drag only previews; save a valid level on release');
  await mkdir('.tmp/qa', { recursive: true });
  await effort.screenshot({ path: '.tmp/qa/effort-pointer-middle.png' });
  await page.mouse.up();
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), 'medium', 'release snaps to the nearest level');
  await slider.press('End');
  assert.equal(await effort.locator('.effort-gem').getAttribute('data-speed'), '3');
  await slider.press('Home');
  assert.equal(await effort.locator('.effort-gem').getAttribute('data-speed'), '1');
  await page.waitForFunction(() => document.querySelector('.effort-gem')?.dataset.state === 'animated');
  const measureSpeed = () => effort.locator('.effort-gem').evaluate(async host => {
    const mount = host.paperShaderMount, original = mount.setFrame, samples = [];
    mount.setFrame = value => { samples.push({ value, time: performance.now() }); original(value); };
    await new Promise(resolve => setTimeout(resolve, 300));
    mount.setFrame = original;
    const rates = samples.slice(1).map((sample, i) => (sample.value - samples[i].value) / Math.min(50, sample.time - samples[i].time)).sort((a, b) => a - b);
    return rates[Math.floor(rates.length / 2)];
  });
  const normalSpeed = await measureSpeed();
  await slider.press('End');
  const fullSpeed = await measureSpeed();
  assert(Math.abs(normalSpeed - .24) < .03 && Math.abs(fullSpeed - .72) < .06, `shader clock accelerates by 200% without remounting: ${normalSpeed} -> ${fullSpeed}`);
  await page.mouse.move(bounds.x + bounds.width - 8, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + 8, bounds.y + bounds.height / 2, { steps: 12 }); await page.mouse.up();
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), 'low', 'pointer drag reaches the lowest valid level');
  await slider.press('ArrowRight');
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), 'medium');
  assert.match(await effort.locator('.effort-slider-thumb').evaluate(el => getComputedStyle(el).transitionProperty), /left/);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => document.querySelector('.effort-gem')?.dataset.state === 'static');
  assert.equal(await effort.locator('canvas').count(), 0, 'reduced motion disposes the decorative shader');
  assert.equal(await effort.locator('.effort-slider-thumb').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await effort.press('Escape');
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  await page.goto(server.resolvedUrls.local[0] + "tests/fixtures/composer-workbench.html?reasoning=other");
  await openEffort();
  assert.equal(await thinking.count(), 0);
  assert.equal(await slider.getAttribute('max'), '1');
  await effort.press('Escape');
  const chooseModel = async name => {
    const menu = page.getByRole('dialog', { name: '选择模型', exact: true });
    if (!await menu.isVisible()) await page.getByRole('button', { name: '选择模型', exact: true }).click();
    await menu.locator('.model-choice').filter({ hasText: name }).click();
  };
  // Switching from another model chooses the model-specific default.
  await chooseModel('Claude Opus 5.5');
  assert.equal(await page.evaluate(() => window.fixtureTask.modelId), "claude-opus-5-5");
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), "medium");
  await chooseModel('Vision');
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), 'high', 'Claude Medium must not leak into High/Max models');
  await openEffort();
  assert.equal(await slider.getAttribute('max'), '1');
  assert.equal(await slider.getAttribute('aria-valuetext'), 'High');
  assert.equal(await page.locator('.thinking-pill').textContent(), 'high');
  await slider.press('End');
  await chooseModel('Vision');
  assert.equal(await page.evaluate(() => window.fixtureTask.effort), 'max', 'Reselecting the same model preserves a valid choice');
  await chooseModel('Claude Opus 5.5');
  await openEffort();
  assert.equal(await slider.getAttribute('aria-valuetext'), 'Medium');
  assert.deepEqual(errors, []);
  console.log("claude reasoning browser: PASS");
} finally { await browser?.close(); await server.close(); }
