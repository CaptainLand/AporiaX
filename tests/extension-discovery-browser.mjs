import assert from "node:assert/strict";
import { createServer } from "vite";
import { chromium } from "playwright-core";
import { mkdtemp } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
const server = await createServer({ server: { host: "127.0.0.1", port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.TEST_BROWSER || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const page = await browser.newPage({ viewport: { width: 1000, height: 1000 } });
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  const url = server.resolvedUrls.local[0] + "tests/fixtures/extension-library.html";
  await page.goto(url);
  const query = page.getByRole("textbox", { name: "在线搜索关键字" });
  await query.fill("fail"); await page.getByRole("button", { name: "搜索", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "Online catalog unavailable" }).waitFor();
  await query.fill("slow"); await page.getByRole("button", { name: "搜索", exact: true }).click();
  await page.waitForFunction(() => !!window.fixture.resolveSlowSearch);
  await query.fill("changed"); await page.evaluate(() => window.fixture.resolveSlowSearch());
  await page.waitForTimeout(80);
  assert.equal(await page.locator(".extension-online-result").count(), 0, "stale search must not overwrite changed query");
  await query.fill("word"); await page.getByRole("button", { name: "搜索", exact: true }).click();
  await page.getByRole("button", { name: /Word report writer/ }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "安装并校验" }).waitFor();
  assert(await dialog.getByText("MIT", { exact: true }).isVisible());
  assert(await dialog.getByText("Python >= 3.10", { exact: true }).isVisible());
  await dialog.getByText("SKILL.md", { exact: true }).click();
  assert.equal(await dialog.locator("script").count(), 0, "upstream content is rendered as inert text");
  await dialog.getByRole("button", { name: "安装并校验" }).click();
  await dialog.getByText("结构与文件完整性验证通过", { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.fixture.installs.length), 1);
  assert(await dialog.getByText("未执行脚本，未验证外部依赖或实际输出质量。").isVisible());
  await dialog.getByRole("button", { name: "重新验证" }).click();
  await page.waitForFunction(() => window.fixture.verifies.length === 1);
  await page.keyboard.press("Escape");
  assert.equal(await page.getByRole("dialog").count(), 0);
  assert.match(await page.evaluate(() => document.activeElement.textContent), /Word report writer/);
  await page.locator(".extension-kind-switch").getByRole("button", { name: "MCP", exact: true }).click();
  await page.getByRole("button", { name: "搜索", exact: true }).click();
  await page.getByRole("button", { name: /Document MCP/ }).click();
  await dialog.getByRole("button", { name: "填写配置并连接" }).click();
  assert.equal(await page.getByRole("dialog").count(), 0);
  assert.match(await page.locator("textarea").inputValue(), /DOCS_TOKEN/);
  assert.equal(await page.getByRole("switch", { name: "Enable for future tasks" }).isChecked(), false);
  await page.getByRole("button", { name: "保存配置", exact: true }).click();
  await page.locator(".extensions-installed-view").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.saves[0].createOnly), true);
  await page.getByRole("button", { name: "探测", exact: true }).first().click();
  await page.locator(".extension-installed-verification").filter({ hasText: "业务调用未验证" }).waitFor();
  const screenshots = await mkdtemp(join(tmpdir(), "aporiax-discovery-ui-"));
  for (const theme of ["light", "dark"]) {
    await page.setViewportSize({ width: 460, height: 860 });
    await page.goto(url + `?theme=${theme}`);
    await query.fill("word"); await page.getByRole("button", { name: "搜索", exact: true }).click();
    await page.getByRole("button", { name: /Word report writer/ }).click();
    await dialog.getByRole("button", { name: "安装并校验" }).waitFor();
    assert(await page.evaluate(() => { const el = document.querySelector(".extension-detail"); return el.scrollWidth <= el.clientWidth + 1 && el.getBoundingClientRect().right <= innerWidth; }), "detail dialog must fit narrow viewport");
    await page.screenshot({ path: join(screenshots, `${theme}.png`) });
    await page.getByRole("button", { name: "关闭扩展详情" }).click();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  }
  assert.deepEqual(errors, []);
  console.log("Online discovery browser: search/error/stale response, license/dependency review, inert upstream text, install/verify, focus restoration, connect/save/probe, narrow light/dark: PASS");
  console.log("Screenshots: " + screenshots);
} finally { await browser?.close(); await server.close(); }
