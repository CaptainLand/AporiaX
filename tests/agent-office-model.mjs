import assert from 'node:assert/strict';
import { buildOfficeModel, officePageRoster, latestOfficeRun } from '../src/office/office-model.js';
import { defaultRoleSettings, defaultRole } from '../shared/professional-roles.js';
import { applyProfessionalAgentEvent } from '../src/conversation/professional-agent-events.js';
import { createWitnessMonitor } from '../electron/witness-monitor.js';

const settings = defaultRoleSettings();
const task = { id: 'office-test', modelId: 'test-model', messages: [] };
let live = false;
let snapshot;
const model = extra => buildOfficeModel({ task, settings, isRunning: live, snapshot, ...extra });
assert.equal(model().roster.length, 6);
assert(model().roster.every(agent => agent.state === 'sleeping'));
const run = { id: 'message', runId: 'run-1', role: 'assistant', status: 'running', content: '', subagents: [], witness: { status: 'running', records: [] } };
task.messages.push(run); live = true;
assert.equal(model().roster[0].state, 'waiting', 'No pretend thinking from a live connection');
run.witness.records = [{ kind: 'thinking', actor: 'main', status: 'running', activityCount: 63 }];
assert.equal(model().roster[0].statusText, '等待模型响应', 'Heartbeat count is not real progress');
run.content = 'Response content';
assert.equal(model().roster[0].state, 'working');
run.content = '';
run.witness.records.push({ kind: 'tool', actor: 'main', status: 'running', tool: 'write_file' });
assert.equal(model().roster[0].detail, 'write_file');
run.witness.records[1].tool = 'collect_subagents';
assert.equal(model().roster[0].state, 'waiting');
assert.equal(model({ isPaused: true }).roster[0].state, 'waiting');
assert.equal(model({ approval: { id: 'approval' } }).roster[0].state, 'attention');
run.clarifications = [{ status: 'pending' }];
assert.equal(model().roster[0].state, 'attention');
run.clarifications = [];
run.witness.records = [];
const emit = (type, patch = {}) => { run.subagents = applyProfessionalAgentEvent(run.subagents, { type, agentId: 'builder-1', role: 'builder', ...patch }); };
emit('subagent.profile', { profileId: 'builder', profileName: '开发', phase: 'queued', task: 'Implement interface' });
assert.equal(model().roster.find(a => a.agentId === 'builder-1').statusText, '等待可用工位');
emit('subagent.started');
assert.equal(model().roster.find(a => a.agentId === 'builder-1').state, 'waiting');
emit('subagent.tool.started', { tool: 'apply_patch' });
assert.equal(model().roster.find(a => a.agentId === 'builder-1').state, 'working');
emit('subagent.tool.completed');
assert.equal(model().roster.find(a => a.agentId === 'builder-1').state, 'waiting');
emit('subagent.phase', { phase: 'approval' });
assert.equal(model().roster.find(a => a.agentId === 'builder-1').state, 'attention');
emit('subagent.phase', { phase: 'waiting_dependencies' });
assert.equal(model().roster.find(a => a.agentId === 'builder-1').statusText, '等待依赖验收');
snapshot = { runId: run.runId, baseWorkers: run.subagents, workers: [{ agentId: 'builder-1', phase: 'queued', budget: { tokens: 123, requests: 2 } }] };
assert.equal(model().roster.find(a => a.agentId === 'builder-1').statusText, '等待可用工位');
emit('subagent.phase', { phase: 'tool' });
assert.equal(model().roster.find(a => a.agentId === 'builder-1').state, 'working', 'New events invalidate older polling snapshots');
emit('subagent.failed', { error: 'Synthetic error' });
assert.equal(model().roster.find(a => a.agentId === 'builder-1').state, 'error');
assert.equal(model().roster.find(a => a.agentId === 'builder-1').controllable, false);
for (let i = 2; i <= 9; i++) emit('subagent.profile', { agentId: `builder-${i}`, profileId: 'builder', profileName: '开发', phase: 'model' });
const roster = model().roster;
assert.equal(roster.filter(a => a.role === 'builder').length, 9, 'Instances do not collapse into their role');
const visible = [];
for (let page = 0; page < Math.ceil((roster.length - 1) / 5); page++) {
  const zone = officePageRoster(roster, page);
  assert(zone.length <= 6); assert.equal(zone[0].id, 'lead'); visible.push(...zone.slice(1).map(a => a.id));
}
assert.deepEqual(visible, roster.slice(1).map(a => a.id));
assert.equal(new Set(roster.map(a => a.id)).size, roster.length);
run.status = 'completed';
assert.equal(model().live, false, 'Terminal status wins over renderer running flag and heartbeat');
assert.equal(model().roster[0].state, 'sleeping');
assert(model().roster.every(a => !a.controllable));
run.status = 'running'; live = false;
assert.equal(model().roster[0].state, 'offline', 'Stale persisted runs are not animated as live');
run.anchorRestoredAt = new Date().toISOString(); live = true;
assert.equal(model().live, false);
assert.equal(model().roster[0].statusText, '已回退');
task.messages.push({ ...run, id: 'steering-archive', isSteeringSegment: true });
assert.equal(latestOfficeRun(task), run);
task.messages.push({ id: 'fresh', runId: 'run-2', role: 'assistant', status: 'running' });
assert.equal(model().roster.filter(a => a.agentId).length, 0, 'Fresh run cannot inherit old workers');
const custom = { ...defaultRole('explore'), id: 'designer', name: '界面设计' };
settings.profiles.push(custom); settings.profiles.find(p => p.id === 'review').enabled = false;
assert(model().roster.some(a => a.id === 'profile:designer'));
assert(!model().roster.some(a => a.id === 'profile:review'));
assert.equal(model({ language: 'en' }).roster[0].statusText, 'Waiting for model');
// Exercise actual producer snapshots, not just hand-authored renderer shapes.
const monitor = createWitnessMonitor({ heartbeatMs: 0 });
const observedTask = { id: 'witness-task', messages: [{ id: 'witness-message', runId: 'witness-run', role: 'assistant', status: 'running' }] };
const observe = event => { monitor.observe(event); observedTask.messages[0].witness = monitor.snapshot(); return buildOfficeModel({ task: observedTask, isRunning: true, settings }); };
try {
  observe({ type: 'turn.started' }); observe({ type: 'response.reset', round: 1 });
  for (let index = 0; index < 63; index++) observe({ type: 'response.activity' });
  assert.equal(observe({ type: 'response.activity' }).roster[0].state, 'waiting');
  assert.equal(observe({ type: 'tool.started', callId: 'write-1', tool: 'write_file' }).roster[0].state, 'working');
  observe({ type: 'tool.completed', callId: 'write-1', tool: 'write_file', success: true });
  observe({ type: 'subagent.started', agentId: 'scout', role: 'explore' });
  let observed = observe({ type: 'subagent.tool.started', agentId: 'scout', role: 'explore', tool: 'read_file', callId: 'read-1' });
  assert.equal(observed.roster.find(a => a.agentId === 'scout').state, 'working');
  assert.equal(observed.roster[0].state, 'waiting', 'Child activity is not attributed to the supervisor');
  observed = observe({ type: 'subagent.tool.completed', agentId: 'scout', role: 'explore', tool: 'read_file', callId: 'read-1', success: true });
  assert.equal(observed.roster.find(a => a.agentId === 'scout').state, 'waiting');
  observed = observe({ type: 'subagent.completed', agentId: 'scout', role: 'explore', status: 'completed' });
  assert.equal(observed.roster.find(a => a.agentId === 'scout').state, 'sleeping');
  assert.equal(observe({ type: 'turn.completed', status: 'completed' }).live, false);
} finally { monitor.dispose(); }
console.log('PASS Agent office model: honest progress, lifecycle/approvals, role configuration, multi-instance zones, stale snapshot and task/run isolation.');
