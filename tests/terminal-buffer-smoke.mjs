import assert from "node:assert/strict";
import { appendTerminalOutput, readTerminalOutput, waitForTerminalOutput, wakeTerminalReaders } from "../electron/workbench/terminal-buffer.js";
import { interactiveTerminalEnvironment } from "../electron/workbench/terminal-environment.js";

const record = { output: "", offset: 0 };
const content = "x".repeat(79999) + "😀" + "y".repeat(81000) + "END_终端";
appendTerminalOutput(record, content);
let cursor = 0, text = "", chunks = 0;
do {
  const read = readTerminalOutput(record, cursor); chunks++;
  assert.ok(!/[\ud800-\udbff]$/.test(read.output));
  assert.ok(!/^[\udc00-\udfff]/.test(read.output));
  text += read.output; cursor = read.cursor;
  if (!read.hasMore) break;
} while (chunks < 10);
assert.equal(chunks, 3); assert.equal(text, content);
assert.equal(readTerminalOutput(record, cursor).output, "");
appendTerminalOutput(record, "z".repeat(400001));
assert.ok(record.output.length <= 400000);
assert.equal(readTerminalOutput(record, 0).cursorExpired, true);
assert.ok(readTerminalOutput(record, Infinity).cursorExpired);
assert.equal(readTerminalOutput(record, 1000000).cursor, record.offset + record.output.length);
const unicode = { output: "😀" + "a".repeat(399999), offset: 0 };
appendTerminalOutput(unicode, "");
assert.ok(!/^[\udc00-\udfff]/.test(unicode.output));
const env = interactiveTerminalEnvironment({ PATH: "fixture", SECRET_TOKEN: "do-not-forward", NODE_OPTIONS: "--inspect" });
assert.equal(env.CI, undefined); assert.equal(env.NO_COLOR, undefined);
assert.equal(env.SECRET_TOKEN, undefined); assert.equal(env.NODE_OPTIONS, undefined);
assert.equal(env.PATH, "fixture");
assert.equal(interactiveTerminalEnvironment({ CI: "1", NO_COLOR: "yes" }).NO_COLOR, "yes");
const live = { output: "", offset: 0, status: "running" };
let awake = false;
const waiting = waitForTerminalOutput(live, 0, 750).then(() => { awake = true; });
await new Promise((done) => setTimeout(done, 15)); assert.equal(awake, false);
appendTerminalOutput(live, "echo"); await waiting; assert.equal(awake, true);
const immediate = performance.now(); await waitForTerminalOutput(live, 0, 750);
assert.ok(performance.now() - immediate < 100, "Buffered data must never wait");
const pending = Array.from({ length: 4 }, () => waitForTerminalOutput(live, 4, 1500));
await assert.rejects(waitForTerminalOutput(live, 4, 1500), /concurrent/);
live.status = "exited"; wakeTerminalReaders(live); await Promise.all(pending);
const exitedAt = performance.now(); await waitForTerminalOutput(live, 4, 1500);
assert.ok(performance.now() - exitedAt < 100, "Exit must wake readers even without output");
live.status = "running";
const timeoutAt = performance.now(); await waitForTerminalOutput(live, 4, 25);
assert.ok(performance.now() - timeoutAt >= 15);
// A timed-out reader is removed; it cannot leak or occupy future wait slots.
const again = Array.from({ length: 4 }, () => waitForTerminalOutput(live, 4, 1500));
appendTerminalOutput(live, "x"); await Promise.all(again);
console.log("PASS: terminal paging/Unicode/expiry, bounded output-triggered reads, timeout/exit cleanup and concurrent limits; explicit environment and credential filtering.");
