import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1000, height: 800 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.resolvedUrls.local[0] + 'tests/fixtures/mention-menu.html');
  const input = page.getByRole('textbox', { name: '任务输入' });
  const plus = page.getByRole('button', { name: '添加内容', exact: true });
  const options = page.getByRole('option');
  await input.fill('保留我的草稿');
  assert.equal(await page.locator('.composer-toolbar .composer-add').count(), 1);
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await plus.click(); await options.first().waitFor();
    assert.deepEqual((await options.locator('strong').allTextContents()).slice(0, 2), ['添加电脑文件', '添加电脑图片']);
    assert.deepEqual(await page.locator('.mention-group-label').allTextContents(), ['添加附件', '项目上下文', '能力与工具']);
    assert.equal(await page.locator('.aporiax-workspace-mention-footer').count(), 0);
    const layout = await options.first().evaluate(el => ({ height: el.getBoundingClientRect().height, direction: getComputedStyle(el.querySelector('span')).flexDirection }));
    assert.equal(layout.height, 36);
    assert.equal(layout.direction, 'row');
    const palette = await page.locator('.aporiax-workspace-mention-menu').boundingBox();
    const composer = await page.locator('.composer').boundingBox();
    assert.ok(palette.width > composer.width * .95);
    assert.equal(await options.count(), 6);
    assert.equal(await input.inputValue(), '保留我的草稿');
    await mkdir('.tmp/qa', { recursive: true });
    await page.mouse.move(5, 5);
    await page.screenshot({ path: `.tmp/qa/composer-add-menu-${theme}.png` });
    await page.locator('.aporiax-workspace-mention-menu').screenshot({ path: `.tmp/qa/composer-add-palette-${theme}.png` });
    await plus.click(); await page.waitForFunction(() => !document.querySelector('.aporiax-workspace-mention-menu'));
    assert.equal(await input.inputValue(), '保留我的草稿');
  }
  await plus.click();
  const cancelEvent = page.waitForEvent('filechooser');
  await options.filter({ hasText: '添加电脑文件' }).click();
  await (await cancelEvent).setFiles([]);
  assert.equal(await input.inputValue(), '保留我的草稿');
  assert.equal(await page.locator('.composer-document-attachment').count(), 0);
  await plus.click();
  const fileEvent = page.waitForEvent('filechooser');
  await options.filter({ hasText: '添加电脑文件' }).click();
  const fileChooser = await fileEvent;
  assert.ok(fileChooser.isMultiple());
  assert.match(await fileChooser.element().getAttribute('accept'), /\.pdf/);
  await fileChooser.setFiles({ name: '演示说明.txt', mimeType: 'text/plain', buffer: Buffer.from('示例') });
  await page.locator('.composer-document-attachment').waitFor();
  assert.equal(await input.inputValue(), '保留我的草稿');
  await plus.click();
  const imageEvent = page.waitForEvent('filechooser');
  await options.filter({ hasText: '添加电脑图片' }).click();
  const imageChooser = await imageEvent;
  assert.match(await imageChooser.element().getAttribute('accept'), /image\/png/);
  await imageChooser.setFiles({ name: '演示图片.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l9sAAAAASUVORK5CYII=', 'base64') });
  await page.locator('.composer-attachments img').waitFor();
  assert.equal(await input.inputValue(), '保留我的草稿');
  await input.fill('之前之后'); await input.evaluate(el => el.setSelectionRange(2, 2));
  await plus.click(); await options.filter({ hasText: 'Skills' }).click();
  await options.filter({ hasText: '新建专业角色' }).click();
  await page.waitForFunction(() => document.querySelector('.composer textarea').value === '之前 @新建专业角色 之后');
  assert.equal(await input.evaluate(el => el.selectionStart), '之前 @新建专业角色 '.length);
  await input.fill('保留 @README');
  await page.getByRole('option', { name: 'README.md' }).waitFor();
  await plus.click(); await options.first().waitFor();
  await input.press('Escape');
  assert.equal(await input.inputValue(), '保留 @README');
  await page.waitForFunction(() => !document.querySelector('.aporiax-workspace-mention-menu'));
  assert.deepEqual(await page.evaluate(() => window.fixture.sends), []);
  await page.setViewportSize({ width: 380, height: 700 });
  await input.fill('窄窗口草稿'); await plus.click(); await options.first().waitFor();
  const menuBox = await page.locator('.aporiax-workspace-mention-menu').boundingBox();
  assert.ok(menuBox.x >= 0 && menuBox.x + menuBox.width <= 380 && menuBox.y >= 0);
  await page.screenshot({ path: '.tmp/qa/composer-add-menu-narrow.png' });
  await options.filter({ hasText: '工作台' }).click();
  await page.getByRole('option', { name: '浏览器', exact: true }).waitFor();
  await input.press('Escape'); assert.equal(await input.inputValue(), '窄窗口草稿');
  await page.goto(server.resolvedUrls.local[0] + 'tests/fixtures/mention-menu.html?text-only');
  await plus.click();
  let opened = false; page.on('filechooser', () => { opened = true; });
  await options.filter({ hasText: '添加电脑图片' }).click();
  await page.waitForFunction(() => window.fixture.notices.length > 0);
  assert.equal(opened, false);
  assert.match(await page.evaluate(() => window.fixture.notices[0]), /仅支持文字/);
  assert.deepEqual(errors, []);
  console.log('PASS one plus button, shared menu with file/image first, native file chooser events, cancel/upload/preview, model image guard, draft/caret preservation and no sends.');
} finally { await browser?.close(); await server.close(); }
