const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { mkdtempSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const { pathToFileURL } = require('node:url');
const { createServer } = require('node:http');
const root = mkdtempSync(join(tmpdir(), 'aporiax-browser-profiles-'));
app.setPath('userData', root); app.disableHardwareAcceleration(); app.on('window-all-closed', () => {});
const timeout = setTimeout(() => { console.error('Profile test timeout'); app.exit(1); }, 30000);
let service, window, server;
app.whenReady().then(async () => {
  const { createWorkbenchService } = await import(pathToFileURL(resolve('electron/workbench/service.js')));
  const { createBrowserProfiles } = await import(pathToFileURL(resolve('electron/workbench/browser-profiles.js')));
  window = new BrowserWindow({ show: false });
  server = createServer((_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<h1>Profile fixture</h1>'); });
  await new Promise(done => server.listen(0, '127.0.0.1', done));
  const url = `http://127.0.0.1:${server.address().port}`;
  service = createWorkbenchService({ getWindow: () => window });
  const context = { taskId: 'profile-task', workspacePath: root };
  const request = input => service.request({ ...context, ...input });
  const temporary = await request({ action: 'new-browser' }); assert.equal(temporary.rememberLogin, false);
  await request({ action: 'navigate', id: temporary.id, url });
  const remembered = await request({ action: 'remember-browser', id: temporary.id, enabled: true });
  assert.equal(remembered.rememberLogin, true);
  const wc = service.resources.get(remembered.id).wc;
  await wc.executeJavaScript("document.cookie='login=fixture; max-age=3600; path=/'; localStorage.setItem('fixture', 'saved')");
  await wc.session.flushStorageData();
  await request({ action: 'stop', id: temporary.id }); await request({ action: 'stop', id: remembered.id });
  const again = await request({ action: 'new-browser' }); await request({ action: 'navigate', id: again.id, url });
  assert.match(await service.resources.get(again.id).wc.executeJavaScript('document.cookie'), /login=fixture/);
  assert.equal(await service.resources.get(again.id).wc.executeJavaScript("localStorage.getItem('fixture')"), 'saved');
  const persisted = createBrowserProfiles(root); await persisted.ready; assert.match(persisted.partition(context), /^persist:/);
  const handle = service.acquire({ ...context, emit: () => {} });
  const child = handle.browserRuntime.forOwner('child');
  const childSnapshot = await child.open({ url }); assert.equal(childSnapshot.capabilities.persistentProfile, false);
  const childResource = [...service.resources.values()].find(item => item.owner === 'agent' && item.id !== again.id);
  assert.equal(await childResource.wc.executeJavaScript('document.cookie'), '');
  await handle.release({ aborted: false });
  assert.equal(childResource.closed, true, 'undelivered child browser must not survive the task');
  assert.equal(childResource.wc.isDestroyed(), true);
  assert.equal(service.resources.has(childResource.id), false);
  assert.equal(service.resources.get(again.id).wc.isDestroyed(), false, 'existing user browser must survive task cleanup');
  const cleared = await request({ action: 'remember-browser', id: again.id, enabled: false });
  assert.equal(cleared.rememberLogin, false);
  const renewed = await request({ action: 'remember-browser', id: cleared.id, enabled: true });
  assert.equal(await service.resources.get(renewed.id).wc.executeJavaScript('document.cookie'), '');
  assert.equal(await service.resources.get(renewed.id).wc.executeJavaScript("localStorage.getItem('fixture')"), null);
  const other = await service.request({ ...context, taskId: 'different', action: 'new-browser' }); assert.equal(other.rememberLogin, false);
  console.log('PASS real Electron opt-in cookie/storage persistence, task isolation, private worker session and clear-login erasure. No real account used.');
}).catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  clearTimeout(timeout); await service?.closeAll(); window?.destroy();
  await new Promise(done => server ? server.close(done) : done());
  await fs.rm(root, { recursive: true, force: true }).catch(error => { if (!['EBUSY', 'EPERM', 'ENOTEMPTY'].includes(error.code)) throw error; });
  app.exit(process.exitCode || 0);
});
