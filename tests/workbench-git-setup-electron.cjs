const { app } = require("electron");
const assert = require("node:assert/strict");
const { mkdtemp, mkdir, writeFile } = require("node:fs/promises");
const { tmpdir } = require("node:os");
const { join } = require("node:path");
const { pathToFileURL } = require("node:url");
let service;
app.whenReady().then(async () => {
  const { createWorkbenchService } = await import(pathToFileURL(join(__dirname, "../electron/workbench/service.js")));
  const { runWorkbenchGit } = await import(pathToFileURL(join(__dirname, "../electron/workbench/git-service.js")));
  const base = await mkdtemp(join(tmpdir(), "aporiax-git-native-"));
  const root = join(base, "repo"), other = join(base, "other"), hooks = join(base, "hooks");
  for (const path of [root, other, hooks]) await mkdir(path);
  service = createWorkbenchService({ getWindow: () => null });
  const context = { taskId: "git-native", workspacePath: root, emit: () => {} };
  const request = (input) => service.request({ ...context, action: "git", ...input });
  const status = () => request({ operation: "status" });
  const mutate = async (input) => request({ revision: (await status()).revision, ...input });
  const git = async (args) => { const result = await runWorkbenchGit(root, args); assert.equal(result.code, 0, result.stderr); return result.stdout.trim(); };
  const active = service.acquire(context);
  await assert.rejects(mutate({ operation: "init" }), /Agent 正在运行/);
  await active.release();
  await mutate({ operation: "init", addIgnore: true });
  await git(["config", "user.name", "Native fixture"]);
  await git(["config", "user.email", "fixture@example.invalid"]);
  await git(["config", "commit.gpgsign", "false"]);
  await git(["config", "core.hooksPath", hooks]);
  await writeFile(join(root, "note.txt"), "Fixture only\n");
  await git(["add", "--", ".gitignore", "note.txt"]);
  await git(["commit", "-m", "Native fixture"]);
  await mutate({ operation: "branch-create", branch: "feature/native" });
  const first = service.acquire({ ...context });
  const second = service.acquire({ ...context, taskId: "other-task-same-root" });
  await assert.rejects(mutate({ operation: "branch-switch", branch: "main" }), /Agent 正在运行/);
  await first.release();
  await assert.rejects(mutate({ operation: "branch-switch", branch: "main" }), /Agent 正在运行/);
  await second.release();
  const unrelated = service.acquire({ ...context, taskId: "unrelated", workspacePath: other });
  await mutate({ operation: "branch-switch", branch: "main" });
  assert.equal((await status()).branch, "main");
  await unrelated.release();
  console.log("PASS: native Workbench service Git routing, active/overlapping task guards, release unblocks and unrelated workspace isolation. Temporary repositories only; no login or network.");
}).then(async () => { await service?.closeAll(); app.exit(0); })
  .catch(async (error) => { console.error(error); await service?.closeAll(); app.exit(1); });
