import assert from 'node:assert/strict';
import { reasoningState, modelSelectionPatch } from '../src/models/reasoning-state.js';
import { quotaResetLabel } from '../src/account/quota-reset.js';
const claude = { id: 'claude', providerId: 'a', supportsThinking: true, thinkingAlwaysOn: true, supportedEfforts: ['low', 'medium', 'high', 'xhigh', 'max'], defaultEffort: 'medium' };
const deepseek = { id: 'deepseek', providerId: 'a', supportsThinking: true };
const task = { modelId: 'claude', providerId: 'a', thinking: true, effort: 'medium' };
assert.equal(modelSelectionPatch(deepseek, task).effort, 'high');
assert.equal(modelSelectionPatch(claude, { ...task, modelId: 'deepseek', effort: 'max' }).effort, 'medium');
assert.equal(modelSelectionPatch(claude, { ...task, effort: 'max' }).effort, 'max');
assert.equal(modelSelectionPatch({ ...claude, providerId: 'b' }, { ...task, effort: 'max' }).effort, 'medium');
assert.equal(reasoningState(deepseek, task).effort, 'high');
assert.equal(reasoningState({ supportsThinking: false }, task).thinking, false);
assert.equal(reasoningState(claude, { thinking: false }).thinking, true);
assert.equal(reasoningState(deepseek, { thinking: false }).thinking, true, 'legacy off preference cannot disable default reasoning');
assert.equal(reasoningState(deepseek).thinking, true);
assert.equal(modelSelectionPatch(deepseek, { ...task, thinking: false }).thinking, true);
const tr = (zh, en, values = {}) => en.replace(/\{(\w+)\}/g, (_, key) => values[key]);
const now = Date.parse('2026-10-14T00:00:00Z');
const label = delta => quotaResetLabel({ cycleEnd: new Date(now + delta).toISOString() }, now, tr);
assert.equal(label((2 * 24 + 3) * 3600000), 'reset 2d 3h');
assert.equal(label(65 * 60000), 'reset 1h 5m');
assert.equal(label(1), 'reset 1m');
assert.equal(label(0), 'reset pending refresh');
assert.equal(label(-1), 'reset pending refresh');
assert.equal(quotaResetLabel({ cycleEnd: 'invalid' }, now, tr), 'reset —');
assert.equal(quotaResetLabel({ activated: false }, now, tr), 'reset not started');
console.log('PASS model switch/default/stale effort normalization and quota reset boundaries.');
