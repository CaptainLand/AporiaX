import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const baseline = process.env.ROUTE_BASELINE === '1';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.TEST_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1200, height: 950 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(`${server.resolvedUrls.local[0]}tests/fixtures/route-activity.html`);
  await page.locator('.route-view').waitFor();
  await mkdir('.tmp/route-activity', { recursive: true });
  if (baseline) {
    assert.equal(await page.locator('.route-run-picker select').isDisabled(), true);
    assert.equal(await page.locator('details.route-block.running[open]').count(), 0);
    assert.equal(await page.getByText('ENOENT: file not found', { exact: true }).count(), 0);
    await page.screenshot({ path: '.tmp/route-activity/before.png' });
    console.log('BASELINE: running actions collapsed; history disabled; failure detail lost.');
  } else {
    const active = page.locator('.ra-current');
    assert.equal(await active.locator('.ra-current-row').count(), 3);
    assert.equal(await active.locator('.ra-current-row').first().locator('strong').innerText(), '等待模型响应', 'Newest active action first');
    await active.locator('.ra-actor').filter({ hasText: '构建 Agent' }).waitFor();
    await active.locator('.ra-actor').filter({ hasText: '验证 Agent' }).waitFor();
    await active.getByText('等待模型响应', { exact: true }).waitFor();
    assert.equal(await active.getByText(/完成.*创建与修改/).count(), 0);
    await page.screenshot({ path: '.tmp/route-activity/after-light.png', fullPage: true });
    const failed = page.locator('.ra-event.failed');
    await failed.getByText('ENOENT: file not found', { exact: true }).waitFor();
    assert.equal(await page.locator('.ra-event').first().getAttribute('data-record-id'), await failed.getAttribute('data-record-id'), 'Newest finished action first');
    await failed.locator('.ra-record-copy').click();
    assert.equal(await page.locator('dialog[open]').count(), 0, 'Row body is selectable, not a modal trigger');
    await failed.getByRole('button').click();
    const dialog = page.locator('dialog[open]');
    await dialog.getByText('退出码', { exact: true }).waitFor();
    assert.equal(await dialog.locator('dd').filter({ hasText: /^1$/ }).count(), 1);
    await dialog.getByRole('button', { name: '在侧栏打开文件', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: '文件不存在：missing.md' }).waitFor();
    await page.screenshot({ path: '.tmp/route-activity/details.png' });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('dialog[open]').count(), 0);
    assert.equal(await failed.getByRole('button').evaluate((el) => el === document.activeElement), true);
    await active.locator('.ra-current-row').filter({ hasText: 'src/account.jsx' }).getByRole('button').click();
    await dialog.getByRole('button', { name: '在侧栏打开文件', exact: true }).click();
    assert.equal(await page.evaluate(() => window.routeFixture.calls.at(-1)?.path), 'src/account.jsx');
    await page.getByRole('button', { name: '计划', exact: true }).click();
    assert.equal(await dialog.locator('.ra-plan li').count(), 2);
    await dialog.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    await page.getByRole('button', { name: '修改 1', exact: true }).click();
    await dialog.locator('.ra-change-list button').click();
    await page.locator('.review-panel').waitFor();
    await page.getByRole('button', { name: '关闭审核', exact: true }).click();
    await page.getByRole('button', { name: '选择任务轮次', exact: true }).click();
    await dialog.locator('.ra-run-list button').last().click();
    await page.getByText('上一轮：检查项目结构', { exact: true }).waitFor();
    await page.evaluate(() => window.routeFixture.emit({ type: 'response.activity' }));
    assert.equal(await page.locator('.ra-heading h2').innerText(), '上一轮：检查项目结构');
    await page.getByRole('button', { name: '回到最新一轮', exact: true }).click();
    await page.evaluate(() => window.routeFixture.emit({ type: 'subagent.tool.completed', agentId: 'builder-1', role: 'builder', callId: 'write', tool: 'write_file', success: true, path: 'src/account.jsx', detail: '已保存 4 行', exitCode: 0 }));
    // emit() schedules a React render; wait for the completed action to leave the active list.
    await active.getByText('写入文件', { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(await active.getByText('写入文件', { exact: true }).count(), 0);
    await page.locator('.ra-event.completed').getByText('src/account.jsx', { exact: true }).waitFor();
    await page.evaluate(() => window.routeFixture.emit({ type: 'subagent.completed', agentId: 'builder-1', summary: '账户页面完成' }));
    await active.locator('.ra-actor').filter({ hasText: '构建 Agent' }).waitFor({ state: 'hidden' });
    assert.equal(await active.locator('.ra-current-row').count(), 2);
    await page.evaluate(() => window.routeFixture.emit({ type: 'control.paused' }));
    await page.getByRole('heading', { name: '暂停中的动作', exact: true }).waitFor();
    assert.equal(await active.locator('.spin').count(), 0);
    await page.evaluate(() => window.routeFixture.emit({ type: 'control.resumed' }));
    await page.evaluate(() => window.routeFixture.bulk());
    const timeline = page.locator('.ra-timeline');
    await timeline.locator('.ra-event').first().locator('.ra-record-copy p').filter({ hasText: /^src\/file-84\.js$/ }).waitFor();
    assert.equal(await timeline.locator('.ra-event').count(), 40);
    assert.equal(await timeline.evaluate((el) => el.scrollTop), 0, 'Following latest stays at the top');
    assert.equal(await timeline.locator('.ra-event').first().locator('.ra-record-copy p').innerText(), 'src/file-84.js');
    await timeline.evaluate((el) => { el.scrollTop = 240; el.dispatchEvent(new Event('scroll')); });
    await page.getByRole('button', { name: '回到最新记录', exact: true }).waitFor();
    const anchor = await timeline.evaluate((el) => {
      const top = el.getBoundingClientRect().top;
      const row = [...el.querySelectorAll('.ra-event')].find((item) => item.getBoundingClientRect().bottom > top + 1);
      return { id: row.dataset.recordId, offset: row.getBoundingClientRect().top - top };
    });
    await page.evaluate(() => window.routeFixture.emit({ type: 'plan.updated', plan: { revision: 3, steps: [] } }));
    const offset = await timeline.evaluate((el, id) => [...el.querySelectorAll('.ra-event')].find((row) => row.dataset.recordId === id).getBoundingClientRect().top - el.getBoundingClientRect().top, anchor.id);
    assert.ok(Math.abs(offset - anchor.offset) < 2, 'Prepended activity must preserve the row being read');
    await page.getByRole('button', { name: /显示更早的记录/ }).click();
    assert.equal(await timeline.locator('.ra-event').count(), 80);
    assert.equal(await timeline.locator('.ra-event').first().locator('strong').innerText(), '计划已更新', 'Loading earlier history must not move it above new records');
    await page.getByRole('button', { name: '回到最新记录', exact: true }).click();
    assert.equal(await timeline.evaluate((el) => el.scrollTop), 0);
    await page.getByRole('button', { name: '需关注', exact: true }).click();
    assert.equal(await timeline.locator('.ra-event').count(), 1);
    await page.getByRole('button', { name: '工具', exact: true }).click();
    assert.equal(await timeline.locator('.ra-event').count(), 40);
    await page.getByRole('button', { name: '全部', exact: true }).click();
    await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
    await page.setViewportSize({ width: 430, height: 900 });
    assert.equal(await page.locator('.route-view').evaluate((el) => el.scrollWidth <= el.clientWidth), true, 'No horizontal overflow on narrow layouts');
    await page.screenshot({ path: '.tmp/route-activity/after-dark-narrow.png', fullPage: true });
    await page.evaluate(() => window.routeFixture.emit({ type: 'response.cloud.queued', limit: 2, source: 'desktop' }));
    await active.getByText('等待 Cloud 模型槽位', { exact: true }).waitFor();
    await active.locator('small').filter({ hasText: /^排队中/ }).waitFor();
    assert.equal(await active.getByText('等待确认', { exact: true }).count(), 0);
    await page.screenshot({ path: '.tmp/route-activity/cloud-queue-dark-narrow.png', fullPage: true });
    await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
    await page.setViewportSize({ width: 1200, height: 950 });
    await page.screenshot({ path: '.tmp/route-activity/cloud-queue-light.png', fullPage: true });
    await page.evaluate(() => window.routeFixture.emit({ type: 'response.cloud.admitted', source: 'desktop' }));
    await active.getByText('等待 Cloud 模型槽位', { exact: true }).waitFor({ state: 'hidden' });
    await active.getByText('等待模型响应', { exact: true }).waitFor();
    await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; window.routeFixture.emit({ type: 'turn.completed', status: 'partial', summary: '部分修改已保存，验证尚未完成' }); });
    await page.locator('.ra-state').filter({ hasText: '部分完成' }).waitFor();
    assert.equal(await page.locator('.ra-current-row').count(), 0);
    await page.getByRole('button', { name: '选择任务轮次', exact: true }).click();
    await dialog.locator('.ra-run-list button').last().click();
    await page.evaluate(() => window.routeFixture.append());
    assert.equal(await page.locator('.ra-heading h2').innerText(), '上一轮：检查项目结构', 'A new run must not steal history selection');
    await page.getByRole('button', { name: '回到最新一轮', exact: true }).click();
    await page.locator('.ra-heading h2').filter({ hasText: '下一轮任务' }).waitFor();
    console.log('Route activity browser: PASS (parallel actions, honest state, errors, dialogs, history, scroll, links, diff, narrow/dark).');
  }
  assert.deepEqual(errors, []);
} finally { await browser?.close(); await server.close(); }
