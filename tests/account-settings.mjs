import assert from 'node:assert/strict';
import { historyQuery, projectRequestHistory } from '../electron/account/request-history.js';
import { usageDay, usageCalendar, summarizeUsage, mergeUsageRows } from '../src/account/usage-model.js';

assert.equal(historyQuery({ accountId: 'a' }), '/usage/requests?days=all&status=all&limit=100');
for (const input of [{}, { accountId: 'a', url: 'https://evil.invalid' }, { accountId: 'a', cursor: 'x&token=y' }, { accountId: 'a', cursor: 42 }, null]) assert.throws(() => historyQuery(input));
const row = { requestId: '1', startedAt: '2024-02-29T16:00:00.000Z', model: 'Fixture', billingStatus: 'settled', billingSource: 'weekly', quotaUsedRatio: .25, tokens: { input: 100, output: 20, cachedInput: 50 }, responseTimeMs: 1234, prompt: 'PRIVATE', apiKey: 'SECRET' };
const projected = projectRequestHistory({ items: [row], sampledAt: '2024-03-02T00:00:00Z', nextCursor: null, token: 'SECRET' });
assert.doesNotMatch(JSON.stringify(projected), /PRIVATE|SECRET/);
assert.equal(projected.items[0].tokens.total, 120);
assert.equal(projectRequestHistory({ ...projected, items: [{ ...row, billingStatus: 'pending' }] }).items[0].tokens, null);
assert.throws(() => projectRequestHistory({ ...projected, items: [], nextCursor: 'loop' }));
assert.throws(() => projectRequestHistory({ ...projected, items: [{ ...row, startedAt: 'bad' }] }));
assert.equal(usageDay(null), null);
assert.equal(usageDay('2024-02-29T15:59:59Z'), '2024-02-29');
assert.equal(usageDay(row.startedAt), '2024-03-01');
const rows = projected.items;
assert.equal(mergeUsageRows(rows, rows).length, 1);
const stats = summarizeUsage([...rows, { ...rows[0], requestId: 'pending', billingStatus: 'pending' }]);
assert.equal(stats.input + stats.output, 120); assert.equal(stats.pending, 1);
const partial = usageCalendar({ rows, sampledAt: projected.sampledAt, complete: false, year: 2024 });
assert.equal(partial.days.length, 366);
assert.equal(partial.days.find(day => day.day === '2024-03-01').covered, false, 'Boundary date can span pages');
assert.equal(partial.days.find(day => day.day === '2024-03-02').covered, true);
assert.equal(partial.days.find(day => day.day === '2024-02-28').unknown, true);
assert.equal(partial.days.find(day => day.day === '2024-03-03').future, true);
const full = usageCalendar({ rows, sampledAt: projected.sampledAt, complete: true, year: 2024 });
assert.equal(full.days.find(day => day.day === '2024-03-01').level, 4);
assert.equal(full.days.find(day => day.day === '2024-02-28').unknown, false);
const quota = usageCalendar({ rows: [{ ...row, quotaUsedRatio: null }], sampledAt: projected.sampledAt, complete: true, year: 2024, metric: 'quota' });
assert.equal(quota.days.find(day => day.day === '2024-03-01').unknown, true);
console.log('PASS account history query/response whitelist, pending/null distinction, deduplication, Beijing midnight/leap year, incomplete boundary and zero/future days.');
