import assert from "node:assert/strict";
import { createServer } from "vite";
import { chromium } from "playwright-core";
import { mkdir } from "node:fs/promises";
const server = await createServer({ server: { host: "127.0.0.1", port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.TEST_BROWSER || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const page = await browser.newPage({ viewport: { width: 1150, height: 800 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(server.resolvedUrls.local[0] + "tests/fixtures/workbench-repairs.html");
  await page.getByText("打开代码", { exact: true }).click();
  await page.locator(".hljs-keyword").first().waitFor();
  assert.equal(await page.locator(".workbench-code-line").count(), 7);
  const colors = await page.locator(".workbench-code").evaluate((el) => [getComputedStyle(el.querySelector(".hljs-keyword")).color, getComputedStyle(el.querySelector(".hljs-string")).color]);
  assert.notEqual(colors[0], colors[1]);
  await mkdir(".tmp/workbench-repairs", { recursive: true });
  await page.screenshot({ path: ".tmp/workbench-repairs/code-light.png" });
  await page.getByRole("button", { name: "编辑", exact: true }).click();
  await page.getByRole("textbox", { name: "代码编辑器" }).fill("// unsaved\nconst keep = 123;");
  await page.evaluate(() => window.wb.openFile("b.js"));
  await page.getByText("const", { exact: true }).first().waitFor();
  await page.evaluate(() => window.wb.select("file:a.js"));
  assert.equal(await page.getByRole("textbox", { name: "代码编辑器" }).inputValue(), "// unsaved\nconst keep = 123;");
  await page.evaluate(() => { window.failSave = true; });
  await page.getByRole("button", { name: "保存", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "File changed externally" }).waitFor();
  await page.evaluate(() => document.documentElement.dataset.theme = "dark");
  await page.screenshot({ path: ".tmp/workbench-repairs/code-dark.png" });
  await page.evaluate(() => window.wb.openFile("readonly.js"));
  await page.getByText("只读预览；截断内容不能覆盖原文件。").waitFor();
  assert.equal(await page.getByRole("button", { name: "编辑", exact: true }).isDisabled(), true);
  await page.evaluate(() => window.wb.openFile("missing.js"));
  await page.getByRole("alert").filter({ hasText: "File does not exist" }).waitFor();
  assert.equal(await page.getByText("正在打开文件", { exact: true }).count(), 0);
  await page.evaluate(() => window.wb.openFile("C:/Temp/photo.png"));
  await page.getByRole("button", { name: "授权只读预览此文件" }).click();
  await page.locator(".workbench-image img").waitFor();
  await page.getByRole("button", { name: "附件.png", exact: true }).click();
  assert.equal(await page.locator(".workbench-image img").getAttribute("src"), await page.getByRole("button", { name: "附件.png", exact: true }).getAttribute("src"));
  await page.getByRole("textbox", { name: "对话输入" }).focus();
  await page.evaluate(() => window.wb.create("terminal"));
  await page.locator(".xterm").waitFor();
  await page.waitForFunction(() => document.activeElement?.classList.contains("xterm-helper-textarea"));
  await page.locator(".workbench-xterm").click();
  await page.keyboard.type("echo test");
  await page.getByRole("button", { name: "中断", exact: true }).click();
  assert.ok((await page.evaluate(() => window.calls)).some((c) => c.action === "interrupt"));
  const terminalScreen = await page.locator(".terminal-session-screen").elementHandle();
  await page.evaluate(() => window.wb.create("terminal"));
  await page.waitForFunction(() => window.calls.some((c) => c.action === "read" && c.id === "terminal_2"));
  await page.evaluate(() => window.wb.select("terminal_1"));
  await page.locator(".terminal-session-screen").waitFor();
  assert.equal(await terminalScreen.evaluate((el) => el === document.querySelector(".terminal-session-screen")), true);
  assert.equal(await page.evaluate(() => window.calls.filter((c) => c.action === "read" && c.id === "terminal_1" && c.cursor === 0).length), 1);
  await page.locator(".workbench-xterm").click();
  await page.screenshot({ path: ".tmp/workbench-repairs/terminal.png" });
  await page.evaluate(async () => { window.failStop = true; await window.wb.close("terminal_1"); });
  await page.getByRole("alert").filter({ hasText: "关闭失败" }).waitFor();
  assert.ok(await page.evaluate(() => window.wb.layout.tabs.some((t) => t.id === "terminal_1")));
  await page.evaluate(async () => { window.failStop = false; await window.wb.close("terminal_1"); });
  assert.equal(await page.evaluate(() => window.wb.layout.tabs.some((t) => t.id === "terminal_1")), false);
  await page.getByText("文件搜索", { exact: true }).click();
  await page.getByRole("textbox", { name: "工作区文件搜索" }).fill("old");
  await page.waitForTimeout(230);
  await page.getByRole("textbox", { name: "工作区文件搜索" }).fill("new");
  await page.getByRole("button", { name: "new.js", exact: true }).waitFor();
  await page.waitForTimeout(600);
  assert.equal(await page.getByRole("button", { name: "old.js", exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log("PASS: syntax colors/rows, draft tab switching, save failure, read-only guard, image approval/attachment, terminal focus/input/interrupt/history, failed close retains tab, search ordering; no browser exceptions.");
} finally { await browser?.close(); await server.close(); }
