import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { defaultAppearance, PRESET_COLORS, validateTheme, themeTokens, contrast } from '../shared/appearance.js';
import { createAppearanceStore } from '../electron/appearance/store.js';
import { createAppearanceTools } from '../electron/runtime/appearance-tools.js';
import { createSkillRegistry } from '../electron/harness/skills/registry.js';
import { prepareSkillMessage } from '../electron/skill-runtime.js';
import { windowThemePalette } from '../electron/window-theme.js';

const root = await mkdtemp(join(tmpdir(), 'aporia-appearance-'));
try {
  const store = await createAppearanceStore(root);
  assert.deepEqual(store.snapshot(), defaultAppearance());
  const draft = { name: '松林', base: 'light', colors: { ...PRESET_COLORS.light, accent: '#16846a', background: '#fcfdfb', panel: '#eef4ee' } };
  validateTheme(draft);
  for (const bad of [{ ...draft, css: 'body{}' }, { ...draft, colors: { ...draft.colors, text: '#ffffff' } }, { ...draft, backgroundId: '../secret.png' }, { ...draft, backgroundStrength: .5 }, { ...draft, base: 'dark' }]) assert.throws(() => validateTheme(bad));
  const palette = themeTokens(validateTheme(draft));
  assert.equal(palette['--bg-navigation'], '#eef4ee');
  assert.ok(contrast(palette['--gray-11'], palette['--gray-1']) >= 4.5);
  assert.deepEqual(windowThemePalette({ base: draft.base, colors: draft.colors }), { backgroundColor: '#fcfdfb', color: '#eef4ee', symbolColor: '#25282d', height: 38 });
  await assert.rejects(store.change({ action: 'save', revision: 0, theme: draft }), /DISABLED/);
  await store.change({ action: 'preferences', revision: 0, enabled: true });
  const tools = createAppearanceTools({ store });
  await tools('create_aporiax_theme', draft);
  assert.equal(store.snapshot().selectedId, null, 'AI cannot apply');
  const id = store.snapshot().themes[0].id;
  await store.change({ action: 'preferences', revision: 2, selectedId: id });
  await assert.rejects(store.change({ action: 'preferences', revision: 3, enabled: false }, { source: 'ai' }), /USER_ONLY/);
  await assert.rejects(store.change({ action: 'save', revision: 0, theme: draft }), /CHANGED/);
  const recovered = await createAppearanceStore(root);
  assert.equal(recovered.snapshot().selectedId, id, 'Restart restores applied theme');
  await recovered.change({ action: 'preferences', revision: 3, enabled: false });
  assert.equal(recovered.snapshot().themes.length, 1, 'Switch off preserves themes');
  await recovered.change({ action: 'preferences', revision: 4, enabled: true });
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l9sAAAAASUVORK5CYII=', 'base64');
  const imageSnapshot = await recovered.importImage(png, 'fixture.png', async data => ({ data, width: 1, height: 1 }));
  assert.match(await recovered.readImage(imageSnapshot.images[0].id), /^data:image\/png;base64/);
  await assert.rejects(recovered.readImage('../../secret'), /INVALID_IMAGE/);
  await assert.rejects(recovered.importImage(Buffer.from('<svg>bad</svg>'), 'fake.png', () => {}), /IMAGE_TYPE/);
  await recovered.change({ action: 'delete', revision: 6, id });
  assert.equal(recovered.snapshot().selectedId, null);
  await writeFile(join(root, 'appearance', 'themes.json'), '{broken');
  const damaged = await createAppearanceStore(root);
  assert.equal(damaged.snapshot().enabled, false); assert.equal(damaged.snapshot().error, 'APPEARANCE_RECOVERED');
  const registry = createSkillRegistry();
  const catalog = await registry.catalog();
  assert.deepEqual(catalog.diagnostics, []);
  const activation = await prepareSkillMessage({ role: 'user', content: '@skill:create-aporiax-theme 帮我设计浅绿色主题' }, '', { registry });
  assert.ok(activation.activatedSkills.some(skill => skill.name === 'create-aporiax-theme'));
  assert.match(activation.aporiaSkillContext, /create_aporiax_theme/);
  console.log('PASS strict theme/contrast validation, atomic persistence/restart, disabled gate, AI candidate never applies, revision conflicts, local image validation/path isolation, corruption fallback and real Skill discovery.');
} finally { await rm(root, { recursive: true, force: true }); }
