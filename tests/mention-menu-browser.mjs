import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false, watch: null } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.TEST_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1000, height: 760 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.resolvedUrls.local[0] + 'tests/fixtures/mention-menu.html');
  const input = page.getByRole('textbox', { name: '任务输入' });
  await mkdir('.tmp/qa', { recursive: true });
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await input.fill('@');
    await page.getByRole('option').filter({ hasText: '文件与目录' }).waitFor();
    if (theme === 'light') assert.deepEqual(await page.evaluate(() => window.fixture.calls), [], 'root categories should not scan sources');
    assert.equal(await page.getByRole('option').count(), 4);
    await page.screenshot({ path: `.tmp/qa/mention-categories-${theme}.png` });
    await input.press('ArrowDown');
    assert.match(await page.getByRole('option', { selected: true }).innerText(), /Skills/);
    await input.press('Enter');
    await page.getByRole('option').filter({ hasText: '新建专业角色' }).waitFor();
    await input.press('ArrowDown');
    assert.match(await page.getByRole('option', { selected: true }).innerText(), /前端审查/);
    await input.press('ArrowUp');
    await page.screenshot({ path: `.tmp/qa/mention-skills-${theme}.png` });
    await input.press('Enter');
    assert.equal(await input.inputValue(), '@新建专业角色 ');
    assert.equal(await page.locator('.aporiax-workspace-mention-menu').count(), 0);
    const highlight = page.locator('.mention-textarea-token');
    assert.equal(await highlight.textContent(), '@新建专业角色');
    const colors = await highlight.evaluate(el => [getComputedStyle(el).color, getComputedStyle(el.parentElement).color]);
    assert.notEqual(colors[0], colors[1]);
    await page.screenshot({ path: `.tmp/qa/mention-highlight-${theme}.png` });
    await input.fill('@'); await input.press('Escape'); await input.press('ArrowRight');
    assert.equal(await page.locator('.aporiax-workspace-mention-menu').count(), 0, 'keyup must not reopen dismissed menu');
    await input.fill(''); await input.fill('@');
    await page.getByRole('option').filter({ hasText: '工作台' }).click();
    await page.getByRole('option', { name: '浏览器', exact: true }).click();
    await page.getByRole('option', { name: /演示页面/ }).waitFor();
    await page.getByRole('button', { name: '返回引用分类' }).click();
    await page.getByRole('option', { name: '终端', exact: true }).click();
    await page.getByRole('option', { name: /开发终端/ }).click();
    assert.equal(await input.inputValue(), '@terminal:terminal_1 ');
    await input.fill('@README');
    await page.getByRole('option', { name: 'README.md' }).waitFor(); await input.press('Tab');
    assert.equal(await input.inputValue(), '@README.md ');
  }
  await input.fill('@新建专业角色');
  await input.press('ArrowLeft'); await input.press('End');
  await page.waitForFunction(() => !document.querySelector('.aporiax-workspace-mention-menu'));
  assert.equal(await page.locator('.aporiax-workspace-mention-menu').count(), 0);
  await input.fill('中文 @README.md\n' + '这是用于验证自动换行与滚动的长句。'.repeat(60) + '\n@新建专业角色 ');
  await input.evaluate(el => { el.scrollTop = el.scrollHeight; el.dispatchEvent(new Event('scroll', { bubbles: true })); });
  const metrics = await input.evaluate(el => {
    const mirror = el.parentElement.querySelector('.mention-textarea-mirror');
    return { width: el.clientWidth, mirrorWidth: mirror.offsetWidth, height: el.scrollHeight, mirrorHeight: mirror.scrollHeight, scroll: el.scrollTop, transform: getComputedStyle(mirror).transform };
  });
  assert.equal(metrics.width, metrics.mirrorWidth);
  assert.ok(Math.abs(metrics.height - metrics.mirrorHeight) < 3, JSON.stringify(metrics));
  assert.ok(metrics.scroll > 0); assert.notEqual(metrics.transform, 'none');
  await input.fill('@新建专业角色 请创建前端审查专家');
  await input.press('Enter');
  assert.deepEqual(await page.evaluate(() => window.fixture.sends), ['@新建专业角色 请创建前端审查专家']);
  await page.setViewportSize({ width: 380, height: 740 }); await input.fill('@');
  await page.getByRole('option').first().waitFor();
  const box = await page.locator('.aporiax-workspace-mention-menu').boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 380 && box.y >= 0);
  await page.mouse.move(5, 5);
  await page.screenshot({ path: '.tmp/qa/mention-categories-narrow.png' });
  await page.mouse.click(10, 10);
  assert.equal(await page.locator('.aporiax-workspace-mention-menu').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS categorized mention menu, subcategories/back, lazy sources, role alias, blue highlights, text wrapping/scroll, keyboard/escape, unchanged submission, both themes and narrow viewport.');
} finally { await browser?.close(); await server.close(); }
